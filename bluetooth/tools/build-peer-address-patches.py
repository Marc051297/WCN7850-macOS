#!/usr/bin/env python3
"""Audit/generate the 25G342 peer-address candidate from assembly and a local binary.

Never modifies the supplied executable. The generated header contains bounded
patch signatures, not Apple's executable. No runtime companion is involved.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
PRISTINE_SHA256 = '5ac2b687fc7781a9c0b22a0e6443ed6ca6f8a6bc5bd0d0c5306ede2e6fa7d1d9'
HELPER_RVA = 0xaa2c18


def macho(data):
    if struct.unpack_from('<I', data)[0] != 0xfeedfacf:
        raise ValueError('Expected thin little-endian Mach-O 64')
    sections, symbols = {}, {}
    pos = 32
    for _ in range(struct.unpack_from('<I', data, 16)[0]):
        cmd, size = struct.unpack_from('<II', data, pos)
        if cmd == 0x19:
            for j in range(struct.unpack_from('<I', data, pos + 64)[0]):
                off = pos + 72 + 80 * j
                name = data[off:off+16].split(b'\0')[0].decode()
                address, length, file_offset = struct.unpack_from('<QQI', data, off+32)
                if name in ('__text', '__qca_decode') and struct.unpack_from('<I', data, off+60)[0]:
                    raise ValueError('Unresolved relocation in injected machine code')
                sections[name] = (address, data[file_offset:file_offset+length])
        elif cmd == 2:
            syms, count, strings, _ = struct.unpack_from('<IIII', data, pos+8)
            for j in range(count):
                idx, _, _, _, value = struct.unpack_from('<IBBHQ', data, syms+16*j)
                end = data.index(b'\0', strings+idx)
                symbols[data[strings+idx:end].decode()] = value
        pos += size
    return sections, symbols


def assemble():
    with tempfile.TemporaryDirectory(prefix='qca-peer-') as tmp:
        obj = Path(tmp) / 'helpers.o'
        subprocess.run(['xcrun', 'clang', '-arch', 'x86_64', '-c',
                        str(ROOT/'compat/QcaPeerAddress25G342.S'), '-o', str(obj)], check=True)
        sections, symbols = macho(obj.read_bytes())
    text_base, helpers = sections['__text']
    _, decode = sections['__qca_decode']
    labels = {k.removeprefix('_qca_peer_'): v-text_base
              for k, v in symbols.items() if k.startswith('_qca_peer_')}
    if len(decode) != 90 or HELPER_RVA + len(helpers) > 0xaa3000:
        raise ValueError('Candidate exceeds audited executable space')
    return helpers, decode, labels


def call(site, destination):
    return b'\xe8' + struct.pack('<i', destination - site - 5)


def build(binary):
    data = Path(binary).read_bytes()
    if hashlib.sha256(data).hexdigest() != PRISTINE_SHA256:
        raise ValueError('Not the audited pristine 25G342 x86_64 bluetoothd')
    sections, _ = macho(data)
    addr, frame = sections['__eh_frame']
    if addr + len(frame) != 0x100aa2bb0 or any(data[0xaa2bb0:0xaa3000]):
        raise ValueError('Executable padding boundary changed')
    helpers, decoder, labels = assemble()
    sites = []

    def site(name, offset, length, changes):
        before = data[offset:offset+length]
        after = bytearray(before)
        for relative, value in changes:
            if relative < 0 or relative + len(value) > length:
                raise ValueError('Patch range overflow')
            after[relative:relative+len(value)] = value
        if data.count(before) != 1 or offset//4096 != (offset+length-1)//4096:
            raise ValueError(f'{name}: signature not unique/single-page')
        sites.append(dict(name=name, offset=offset, before=before, after=bytes(after)))

    def redirect(offset, original, label):
        if data[offset:offset+5] != call(offset, original):
            raise ValueError(f'Native call ABI changed at {offset:#x}')
        return call(offset, HELPER_RVA+labels[label])

    site('Helpers', 0xaa2ba0, HELPER_RVA-0xaa2ba0+len(helpers),
         [(HELPER_RVA-0xaa2ba0, helpers)])
    site('Legacy', 0x20c3dd, 29, [(15, redirect(0x20c3ec, 0x223424, 'clear'))])
    site('Retain', 0x2234c3, 30,
         [(15, call(0x2234d2, HELPER_RVA+labels['keep']) + b'\x90'*10)])
    site('Decode', 0x729844, 90, [(0, decoder)])
    site('Device', 0x717012, 32,
         [(5, call(0x717017, HELPER_RVA+labels['device']) + b'\x90'*4)])
    site('Connect', 0x7140d3, 49,
         [(6, redirect(0x7140d9, 0x714166, 'list')),
          (44, redirect(0x7140ff, 0x706900, 'get'))])
    site('Update', 0x6d11ea, 196,
         [(14, redirect(0x6d11f8, 0x714166, 'list')),
          (191, redirect(0x6d12a9, 0x706900, 'get'))])
    site('Extended', 0x20dc4a, 46,
         [(32, redirect(0x20dc6a, 0x223424, 'extended'))])
    return helpers, decoder, labels, sites


def header(sites):
    lines = ['// SPDX-License-Identifier: MIT',
             '// Generated by tools/build-peer-address-patches.py. 25G342 x86_64 ONLY.',
             '// Offline candidate: requires verified page-lifetime integration.',
             '#pragma once', '#include <stddef.h>', '#include <stdint.h>',
             'namespace QcaPeerPatches {',
             'struct Site { const char *name; const uint8_t *find, *replace; size_t size; };']
    for s in sites:
        for kind, value in [('Find', s['before']), ('Replace', s['after'])]:
            lines.append('static const uint8_t '+s['name']+kind+'[] = {')
            lines += ['    '+', '.join(f'0x{x:02x}' for x in value[i:i+16])+','
                      for i in range(0, len(value), 16)]
            lines.append('};')
    lines.append('static const Site sites[] = {')
    lines += ['    {"'+s['name']+'", '+s['name']+'Find, '+s['name']+'Replace, sizeof('+s['name']+'Find)},'
              for s in sites]
    lines += ['};', '}']
    return '\n'.join(lines)+'\n'


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('binary', type=Path)
    p.add_argument('--write-header', type=Path)
    args = p.parse_args()
    helpers, decoder, labels, sites = build(args.binary)
    if args.write_header:
        args.write_header.write_text(header(sites))
    print(json.dumps({'build':'25G342', 'binary_sha256':PRISTINE_SHA256,
                      'helper_bytes':len(helpers), 'decode_bytes':len(decoder),
                      'helper_rvas':{k:hex(HELPER_RVA+v) for k,v in labels.items()},
                      'sites':[{'name':s['name'], 'offset':hex(s['offset']), 'size':len(s['before'])}
                               for s in sites]}, indent=2))
