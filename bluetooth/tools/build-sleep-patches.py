#!/usr/bin/env python3
"""Audit additive sleep bridges against a local pristine binary, never modify it.

The helper anchor depends on the unchanged experimental.8 peer helper. Apple
executables, disassembly and hardware logs are deliberately not packaged.
"""
import argparse
import importlib.util
from pathlib import Path
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
HELPER_RVA = 0xaa2e00
spec = importlib.util.spec_from_file_location('peer_patches', ROOT/'tools/build-peer-address-patches.py')
peer = importlib.util.module_from_spec(spec)
spec.loader.exec_module(peer)


def assemble():
    with tempfile.TemporaryDirectory(prefix='qca-sleep-') as tmp:
        obj = Path(tmp)/'sleep.o'
        subprocess.run(['xcrun', 'clang', '-arch', 'x86_64', '-c',
                        str(ROOT/'compat/QcaSleep25G342.S'), '-o', str(obj)], check=True)
        sections, symbols = peer.macho(obj.read_bytes())
    base, code = sections['__text']
    labels = {k.removeprefix('_qca_sleep_'): v-base
              for k, v in symbols.items() if k.startswith('_qca_sleep_')}
    if HELPER_RVA+len(code) > 0xaa3000:
        raise ValueError('Sleep helper exceeds audited padding')
    return code, labels


def build(binary):
    _, _, _, old_sites = peer.build(binary)  # includes exact pristine SHA-256
    pristine = Path(binary).read_bytes()
    data = bytearray(pristine)
    for site in old_sites:
        start = site['offset']
        data[start:start+len(site['after'])] = site['after']
    code, labels = assemble()
    sites = []

    def add(name, offset, size, changes):
        before = bytes(data[offset:offset+size])
        after = bytearray(before)
        for relative, value in changes:
            if relative < 0 or relative+len(value) > size:
                raise ValueError('Sleep patch overflow')
            after[relative:relative+len(value)] = value
        if data.count(before) != 1 or offset//4096 != (offset+size-1)//4096:
            raise ValueError(f'{name}: signature is not unique/single-page')
        sites.append(dict(name=name, offset=offset, before=before, after=bytes(after)))

    # Anchor on the unchanged final peer-helper instructions; change padding only.
    if any(pristine[0xaa2d74:0xaa3000]):
        raise ValueError('Expected unused executable padding after peer helper')
    add('Helpers', 0xaa2d60, HELPER_RVA+len(code)-0xaa2d60,
        [(HELPER_RVA-0xaa2d60, code)])
    prologue = bytes.fromhex('55 48 89 e5 53')
    if pristine[0x3224cc:0x3224d1] != prologue:
        raise ValueError('Native HID helper prologue changed')
    add('Hid', 0x3224cc, 32,
        [(0, b'\xe9'+struct.pack('<i', HELPER_RVA+labels['hid']-0x3224cc-5))])
    if pristine[0x218065:0x21806c] != bytes.fromhex('48 85 05 54 a2 93 00'):
        raise ValueError('Native manufacturer mask TEST changed')
    add('Idle', 0x218059, 25,
        [(12, peer.call(0x218065, HELPER_RVA+labels['idle'])+b'\x90\x90')])
    # Native Core instance publication, sleep flags, mask setter and parser
    # control flow establish the fields used above; fail if their ABIs change.
    checks = {
        0x394de1: 'e8421108004c8935e35d7a00',
        0x4154b9: '66c783890500000000',
        0x41a454: 'c6838a05000001',
        0x41a84d: 'c6838905000001',
        0x41bab1: '41c6878a05000003',
        0x41bac8: '41c60704',
        0x41b60d: 'c6838905000000',
        0x2176b7: '48891d02ac9300',
        0x7269c9: 'bf00002000',
        0x2180ec: 'e8c69fedff48890568f79100',
        0x21810f: '488d3d5956000031f6ba0a000000',
    }
    for offset, expected in checks.items():
        if pristine[offset:offset+len(bytes.fromhex(expected))] != bytes.fromhex(expected):
            raise ValueError(f'Native sleep ABI changed at {offset:#x}')
    return code, labels, sites


def header(sites):
    lines = ['// SPDX-License-Identifier: MIT',
             '// Generated by tools/build-sleep-patches.py. Additive to experimental.8.',
             '// Audited 25G342 x86_64 ONLY. Never install outside the verified page guard.',
             '#pragma once', '#include <stddef.h>', '#include <stdint.h>',
             'namespace QcaSleepPatches {',
             'struct Site { uint32_t offset; const uint8_t *find, *replace; size_t size; };']
    for site in sites:
        for kind, value in [('Find', site['before']), ('Replace', site['after'])]:
            lines.append('static const uint8_t '+site['name']+kind+'[] = {')
            lines += ['    '+', '.join(f'0x{x:02x}' for x in value[i:i+16])+','
                      for i in range(0, len(value), 16)]
            lines.append('};')
    lines.append('static const Site sites[] = {')
    lines += [f'    {{0x{s["offset"]:x}, {s["name"]}Find, {s["name"]}Replace, sizeof({s["name"]}Find)}},'
              for s in sites]
    lines += ['};', '}']
    return '\n'.join(lines)+'\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('binary', type=Path)
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    code, labels, sites = build(args.binary)
    result = header(sites)
    if args.output:
        args.output.write_text(result)
    print(f'Audited {len(sites)} sleep sites; {len(code)} helper bytes; labels {labels}')
